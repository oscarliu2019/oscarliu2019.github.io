const createSoup = entry => {
  const normalizePattern = pattern => {
    if (typeof pattern !== 'string') return pattern;
    const polarityText = pattern.replace(/有没有|是不是|会不会|能不能/g, '');
    if (/(不是|没有|并非|不能|不会|无法|不真)/.test(polarityText)) {
      return { text: pattern, verdict: 'yes' };
    }
    return pattern;
  };
  const facts = entry.clues.map(clue => ({
    id: `${entry.id}_${clue.id}`,
    text: clue.text,
    core: clue.core !== false
  }));
  const questionNodes = entry.clues.map(clue => ({
    id: `${entry.id}_q_${clue.id}`,
    question: clue.question,
    verdict: clue.verdict || 'yes',
    reply: clue.reply || clue.text,
    reveals: [`${entry.id}_${clue.id}`],
    keywords: clue.keywords,
    patterns: clue.patterns.map(normalizePattern),
    strict: Boolean(clue.strict),
    requires: (clue.requires || []).map(id => `${entry.id}_${id}`)
  }));
  const decoyStatements = entry.decoys.map((decoy, index) => typeof decoy === 'string'
    ? { id: `${entry.id}_d${index + 1}`, text: decoy }
    : { id: `${entry.id}_d${index + 1}`, ...decoy }
  );
  return {
    ...entry,
    facts,
    questionNodes,
    solutionFactIds: facts.filter(fact => fact.core).map(fact => fact.id),
    decoyStatements
  };
};

